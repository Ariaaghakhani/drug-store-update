// Static registry of every panel menu this frontend can render.
// `key` is the stable id of the menu. `modules` joins it to BACK: `POST /api/auth/me/permissions` returns the user's
// `{module, action, allowed}` grants, and a staff user sees a menu when they hold READ on any of its `modules`
// (module names are BACK's `@EndpointInfo(module = …)`). `always: true` menus show for every logged-in user.
// Optional `flag`: a StoreProfileDTO boolean (GET /api/store-profile) that must be true for the menu to show.
// Optional `group`: a key of GROUP_LABELS. The desktop sidebar (pages/panel.vue) renders a heading when the group
// changes and a divider between grouped and ungrouped entries; entries without `group` render exactly as before.
// To add a menu: add an entry here (+ its page under pages/panel/) with the BACK module(s) guarding its endpoints.
// Every entry must have a page, or it links to a 404. Not built yet, so not listed: reports (REPORT), analytics, finance. Purchase orders (PURCHASE_ORDER) is listed from C2a, under the stock group. Settings (SYSTEM_SETTINGS, PAYMENT_GATEWAY, MY_ORGANIZATION) is listed from C5a and shows only its tabs the user can read. Customer wallets (WALLET, `/panel/wallets`) is listed from C6a. Store customers (STORE_CUSTOMER, STORE_CUSTOMER_ADMIN, `/panel/customers`) is listed from C7a. The blog (BLOG_POST, BLOG_COMMENT, BLOG_TAG, `/panel/blog`) is listed from C9a, under the content group after questions. Contact messages (CONTACT, `/panel/contact`) is listed from C10a, under the content group after blog. Info pages (ABOUT_US, TERMS, RETURN_POLICY, `/panel/pages`) is listed from C11a, under the content group after contact. Goods attributes (GOODS_ATTRIBUTE, `/panel/attributes`) is listed from C13a, under the stock group after purchase orders. Bulk imports (GOODS, `/panel/imports`) is listed from C14a, under the stock group after attributes. Stock movements (INVENTORY, `/panel/stock-movements`) is listed from C15a, under the stock group after imports. Demand insights (WISHLIST, STOCK_ALERT, GLOBAL_SEARCH, `/panel/insights`) is listed from C15b, under the insights group after the info pages. Prescriptions (PRESCRIPTION, `/panel/prescriptions`, flag `prescriptionEnabled`) is listed from B11a, under the sales group after wallets; the customer fallback gains it after returns (the owner fallback gains it after wallets with the staff list and detail in C17a–C17c). The workflow task inbox (WORKFLOW_TASK, `/panel/tasks`, label «کارتابل») is listed from C19a, as the first entry of the workflow group after insights; its sidebar badge (open tasks) is set by pages/panel.vue, not here. The next workflow entry (`workflow`, C20a) follows it.
